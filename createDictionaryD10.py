# Program to create a simple dictionary and check its functionality

# Empty Dictionary
my_dict = {}
print(my_dict)

# Dictionary with integer keys 
my_dict = {1: "male", 2: "female"}
print(my_dict)

# Dictionary with mixed keys
my_dict = {"name": "Adit", 1: [100, 200, 3]}
print(my_dict)

# Using dict()
my_dict = dict({1: "glass", 2: "bat"})
print(my_dict)

# From sequence having each item as a pair
my_dict = dict([(1, "a"), (2, "b")])
print(my_dict)

