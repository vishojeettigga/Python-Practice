# Program to explain the relational operators (>,<) using user input
x = int(input("Enter the value of x: "))
y = int(input("Enter the value of y: "))

print("The value returned by the x>y expression is: ")
print(x>y) # Greater than operator
print("\n") # Insert new line

print("The value returned by the x<y expression is: ")
print(x<y) # Less than operator
print("\n") # Insert new line