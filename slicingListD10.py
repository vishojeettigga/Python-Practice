# Program to check working of Slicing of List

my_list = [1, 2, 5, 4, 5]

# Format for list slicing is [start:stop:step]

# Print to get all the items without any specific position 
print(my_list[:])


# Print to get all the items with start position
print(my_list[2:])


# Print to get all the items after a specific position
print(my_list[:2])


# Print to get all the items before a specific position
print(my_list[2:4])


# Print to get all the items from one position to another position
print(my_list[::2])

