# program to create different types of tuples

# Empty tuple
my_tuple = ()
print(my_tuple)

# Tuple having integers
my_tuple = (10, 100, 1000)
print(my_tuple)

# Tuple having mixed data types
my_tuple = (1, "SCHOOL", 3.4)
print(my_tuple)

# Nested tuple
my_tuple = ("COMPUTER", [200, 100, 6], (1, 10, 3))
print(my_tuple)

# End of program